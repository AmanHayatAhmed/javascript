// Function Name: celsiusToFahrenheit

// Parameters:

// celsius (number) - temperature in degrees Celsius.

// Return:

// The temperature converted to degrees Fahrenheit.

// Formula:

// Use the formula to convert Celsius to Fahrenheit: Fahrenheit = (Celsius * 9/5) + 32.

function celsiusToFahrenheit (celsius) {
    return Fahrenheit = (celsius * 9/5) + 32

}
